import { z } from "zod";
const text = z.string();
const number = z.number().finite();
const intent = z.enum(["Informationnelle", "Commerciale", "Transactionnelle"]);
const platform = z.enum([
  "ChatGPT Search",
  "Google AI Overviews",
  "Microsoft Copilot",
  "Perplexity",
  "Gemini",
]);
const keywordPlanSchema = z.object({
  stage: z.enum([
    "À qualifier",
    "À cibler",
    "À intégrer",
    "Intégré",
    "À optimiser",
    "À surveiller",
    "Archivé",
  ]),
  priority: z.enum(["Critique", "Haute", "Moyenne", "Basse"]),
  owner: text,
  targetPosition: number.int().min(1).max(100).nullable(),
  placements: z.array(text),
  contentUrl: text,
  updatedAt: text,
});
const measurementSchema = z.object({
  id: text,
  date: text,
  position: number.min(1).max(100).nullable(),
  impressions: number.min(0),
  clicks: number.min(0),
  source: text,
  notes: text,
});
const keyword = z.object({
  id: text,
  term: text,
  family: text,
  intent,
  position: number.nullable(),
  previous: number.nullable(),
  volume: number.nullable(),
  difficulty: number.nullable(),
  url: text,
  history: z.array(z.object({ week: text, position: number.nullable() })),
  competitors: z.array(z.object({ name: text, position: number })),
  lastCheck: text,
  notes: text,
  plan: keywordPlanSchema.optional(),
  measurements: z.array(measurementSchema).optional(),
});
const prompt = z.object({
  id: text,
  question: text,
  category: text,
  intent,
  platform,
  frequency: z.enum(["Hebdomadaire", "Bimensuelle", "Mensuelle"]),
});
const test = z.object({
  id: text,
  promptId: text,
  date: text,
  platform,
  question: text,
  mentioned: z.boolean(),
  recommended: z.boolean(),
  accuracy: z.enum(["Exacte", "Partielle", "Incorrecte", "—"]),
  mentionPosition: number.nullable(),
  competitors: z.array(text),
  sources: z.array(text),
  status: z.enum([
    "Mentionnée et recommandée",
    "Mentionnée sans recommandation",
    "Non mentionnée",
    "Réponse incorrecte",
  ]),
  response: text,
  origin: z.enum(["Simulation", "Saisie manuelle"]).optional(),
  evidenceUrl: text.optional(),
});
const action = z.object({
  id: text,
  title: text,
  description: text,
  category: z.enum(["SEO", "GEO"]),
  priority: z.enum(["Critique", "Haute", "Moyenne", "Basse"]),
  owner: text,
  start: text,
  due: text,
  status: z.enum(["À faire", "En cours", "En attente", "Terminé", "Bloqué"]),
  target: text,
  deliverable: text,
  kpi: text,
  comments: text,
  recurrence: z
    .enum(["Ponctuelle", "Hebdomadaire", "Bimensuelle", "Mensuelle", "Trimestrielle"])
    .optional(),
  parentActionId: text.optional(),
  keywordId: text.optional(),
  promptId: text.optional(),
  pageId: text.optional(),
  baseline: number.nullable().optional(),
  goal: number.nullable().optional(),
  result: number.nullable().optional(),
  metricUnit: text.optional(),
  proofUrl: text.optional(),
});
const page = z.object({
  id: text,
  name: text,
  url: text,
  type: z.enum([
    "Page solution",
    "Page secteur",
    "Étude de cas",
    "Article de blog",
    "Page institutionnelle",
  ]),
  family: text,
  mainKeyword: text,
  keywordCount: number,
  published: z.enum(["Publiée", "Brouillon", "À créer", "À vérifier"]),
  indexed: z.enum(["Indexée", "Non indexée", "En attente", "À vérifier"]),
  score: number.nullable(),
  clicks: number.nullable(),
  lastOptimized: text,
  owner: text,
  title: text,
  meta: text,
  h1: text,
  h2: text,
  canonical: text,
  internalLinks: number,
  schema: text,
  geoContent: z.boolean(),
});
const lead = z.object({
  id: text,
  company: text,
  source: z.enum(["SEO", "GEO", "Direct", "Référent"]),
  channel: text,
  origin: text,
  date: text,
  status: z.enum(["Nouveau", "Qualifié", "Rendez-vous", "Proposition", "Client", "Perdu"]),
  owner: text,
  value: number,
});
const backlink = z.object({
  id: text,
  domain: text,
  source: text,
  target: text,
  type: z.enum(["Dofollow", "Nofollow", "Sponsorisé", "UGC"]),
  authority: number.min(0).max(100).nullable(),
  date: text,
  status: z.enum(["Actif", "Perdu", "En attente"]),
  quality: z.enum(["Excellente", "Bonne", "Moyenne", "Faible"]),
});
const competitor = z.object({
  id: text,
  name: text,
  site: text,
  commonKeywords: number.min(0).nullable(),
  seoVisibility: number.min(0).max(100).nullable(),
  shareOfVoice: number.min(0).max(100).nullable(),
  geoPresence: number.min(0).max(100).nullable(),
  aiCitations: number.min(0).nullable(),
  topTerms: z.array(text),
});
export const stateSchema = z.object({
  backlinks: z.array(backlink).default([]),
  competitors: z.array(competitor).default([]),
  keywords: z.array(keyword),
  families: z.array(text),
  prompts: z.array(prompt),
  geoTests: z.array(test),
  actions: z.array(action),
  pages: z.array(page),
  leads: z.array(lead),
  audits: z
    .array(
      z.object({
        id: text,
        pageId: text,
        checkId: text,
        status: z.enum(["À vérifier", "Conforme", "À corriger", "Non applicable"]),
        notes: text,
        evidenceUrl: text,
        checkedAt: text,
      }),
    )
    .default([]),
  period: z.enum(["7j", "30j", "90j", "12m"]),
});
export type DemoState = z.infer<typeof stateSchema>;
